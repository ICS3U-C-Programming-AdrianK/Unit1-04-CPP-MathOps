#include <iostream>
#include <cmath>

int main() {
    std::cout << "2+3=" <<2+3 << std::endl;  // addition
    std::cout << "9-4=" <<9-4 << std::endl;  // subtraction
    std::cout << "7*5=" <<7*5 << std::endl;  // multiplication
    std::cout << "4/2=" <<4/2 << std::endl;  // integer division
    std::cout << "7/2=" <<7.0/2 << std::endl;  // decimal division
    std::cout << "5%2=" <<5%2 << std::endl;  // modulo
    std::cout << "9^2=" <<pow(9 , 2) << std::endl;  // exponent
    std::cout << "√64=" <<sqrt(64) << std::endl;  // square root
}
